export type TKey = keyof typeof uk;
type StrKey = { [K in TKey]: (typeof uk)[K] extends string ? K : never }[TKey];
type ArrKey = Exclude<TKey, StrKey>;

const dicts: Record<Lang, Dict> = { uk: uk as Dict, en };

const fill = (s: string, vars?: Record<string, string | number>) =>
  vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`)) : s;

export function makeT(lang: Lang) {
  const d = dicts[lang] || dicts.uk;
  const t = (key: StrKey, vars?: Record<string, string | number>) =>
    fill(((d[key] as string) ?? (dicts.uk[key] as string) ?? key) as string, vars);
  const pick = (key: ArrKey, vars?: Record<string, string | number>) => {
    const arr = (d[key] as string[]) || (dicts.uk[key] as string[]);
    return fill(arr[Math.floor(Math.random() * arr.length)], vars);
  };
  const err = (code: string) => {
    const k = `err.${code}` as StrKey;
    return (d as any)[k] ? t(k) : t('err.generic');
  };
  return { t, pick, err };
}

export type T = ReturnType<typeof makeT>['t'];
